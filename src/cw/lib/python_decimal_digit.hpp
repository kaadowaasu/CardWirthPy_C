#pragma once
#include <cstdint>
#include <optional>

namespace cw::lib {
// 元の Pipfile の Python 3.8 は UCD 12.1 を使う。参照環境に合わ
// せ、以前の Python 3.11/UCD14 の整数分類から意図的に切り替える。int/Decimal
// の文字列文法は別々に保つ。出典: unicode.org/Public/12.1.0/ucd/extracted/DerivedNumericType.txt
// （Nd）。
inline std::optional<unsigned> python_decimal_digit(std::uint32_t codepoint) noexcept
{
    static constexpr std::uint32_t zeros[]{
        0x0030,0x0660,0x06f0,0x07c0,0x0966,0x09e6,0x0a66,0x0ae6,0x0b66,0x0be6,
        0x0c66,0x0ce6,0x0d66,0x0de6,0x0e50,0x0ed0,0x0f20,0x1040,0x1090,0x17e0,
        0x1810,0x1946,0x19d0,0x1a80,0x1a90,0x1b50,0x1bb0,0x1c40,0x1c50,0xa620,
        0xa8d0,0xa900,0xa9d0,0xa9f0,0xaa50,0xabf0,0xff10,0x104a0,0x10d30,0x11066,
        0x110f0,0x11136,0x111d0,0x112f0,0x11450,0x114d0,0x11650,0x116c0,0x11730,0x118e0,
        0x11c50,0x11d50,0x11da0,0x16a60,0x16b50,0x1d7ce,0x1d7d8,0x1d7e2,0x1d7ec,0x1d7f6,
        0x1e140,0x1e2f0,0x1e950,
    };
    for (const auto zero : zeros)
        if (codepoint >= zero && codepoint < zero + 10) return codepoint - zero;
    return std::nullopt;
}
}
