Real80 Real80::parse(const std::string_view input) {
    if (input.empty()) invalid_real80(input);

    std::size_t position = 0;
    bool negative = false;
    bool explicitly_positive = false;
    switch (input[position]) {
    case '-':
        negative = true;
        ++position;
        if (position == input.size()) invalid_real80(input);
        if (ascii_lower(input[position]) == 'i') {
            // Phobosと同様、符号の分岐で負の無限大を認識する。 先
            // 頭のプラスはこの分岐に入らないため、+inf は拒否する。
            if (position + 2 < input.size() &&
                ascii_lower(input[position + 1]) == 'n' &&
                ascii_lower(input[position + 2]) == 'f' &&
                position + 3 == input.size()) {
                return Real80::infinity(true);
            }
            invalid_real80(input);
        }
        break;
    case '+':
        explicitly_positive = true;
        ++position;
        if (position == input.size()) invalid_real80(input);
        break;
    default:
        break;
    }

    if (ascii_lower(input[position]) == 'i') {
        if (position + 3 == input.size() &&
            ascii_lower(input[position + 1]) == 'n' &&
            ascii_lower(input[position + 2]) == 'f' && !negative && !explicitly_positive) {
            return Real80::infinity();
        }
        invalid_real80(input);
    }
    if (ascii_lower(input[position]) == 'n') {
        if (position + 3 != input.size() ||
            ascii_lower(input[position + 1]) != 'a' ||
            ascii_lower(input[position + 2]) != 'n') {
            invalid_real80(input);
        }
        // Phobosと同様、NaNの分岐では先行する符号を無視する。
        return Real80::nan();
    }

    bool is_hexadecimal = false;
    const bool starts_with_zero = input[position] == '0';
    if (starts_with_zero) {
        ++position;
        if (position == input.size()) return Real80::zero(negative);
        is_hexadecimal = input[position] == 'x' || input[position] == 'X';
        if (is_hexadecimal) ++position;
    }

    std::uint64_t msdec = 0;
    std::uint64_t lsdec = 0;
    std::uint64_t msscale = 1;
    int exponent = 0;
    int dot = 0;
    bool saw_digits = false;

    // D版は32ビットの int を直接使うが、ここでは飽和させる。 何十億桁もの仮
    // 数を持つ入力でも、符号付き整数のオーバーフローによる未定義動作を起こさない。
    const auto add_exponent = [&exponent](const int amount) {
        if (amount > 0 && exponent > std::numeric_limits<int>::max() - amount) {
            exponent = std::numeric_limits<int>::max();
        } else if (amount < 0 && exponent < std::numeric_limits<int>::min() - amount) {
            exponent = std::numeric_limits<int>::min();
        } else {
            exponent += amount;
        }
    };

    const unsigned int base = is_hexadecimal ? 16U : 10U;
    const int exp_iter = is_hexadecimal ? 4 : 1;
    const std::uint64_t msscale_max = is_hexadecimal ? hexadecimal_scale_max : decimal_scale_max;
    saw_digits = !is_hexadecimal && starts_with_zero;

    while (position < input.size()) {
        char current = input[position];
        const auto is_digit = [is_hexadecimal](const char value) {
            return is_hexadecimal ? is_hex_digit(value) : is_decimal_digit(value);
        };
        const auto digit_value = [is_hexadecimal](const char value) -> unsigned int {
            if (!is_hexadecimal || !is_ascii_alpha(value)) return static_cast<unsigned int>(value - '0');
            return static_cast<unsigned int>((value & ~0x20) - ('A' - 10));
        };

        while (is_digit(current)) {
            saw_digits = true;
            const auto digit = static_cast<std::uint64_t>(digit_value(current));
            if (msdec < (std::numeric_limits<std::uint64_t>::max() - base) / base) {
                msdec = msdec * base + digit;
            } else if (msscale < msscale_max) {
                lsdec = lsdec * base + digit;
                msscale *= base;
            } else {
                add_exponent(exp_iter);
            }
            add_exponent(-dot);

            ++position;
            if (position == input.size()) break;
            current = input[position];
            if (current == '_') {
                ++position;
                if (position == input.size()) break;
                current = input[position];
            }
        }
        if (position < input.size() && input[position] == '.' && dot == 0) {
            ++position;
            dot += exp_iter;
            continue;
        }
        break;
    }

    if (!saw_digits) invalid_real80(input);
    if (is_hexadecimal &&
        (position == input.size() || (input[position] != 'p' && input[position] != 'P'))) {
        invalid_real80(input);
    }

    if (is_hexadecimal ||
        (position < input.size() && (input[position] == 'e' || input[position] == 'E'))) {
        ++position;
        if (position == input.size()) invalid_real80(input);
        bool negative_exponent = false;
        if (input[position] == '-') {
            negative_exponent = true;
            ++position;
        } else if (input[position] == '+') {
            ++position;
        }
        bool exponent_digits = false;
        int parsed_exponent = 0;
        for (; position < input.size() && is_decimal_digit(input[position]); ++position) {
            const int digit = input[position] - '0';
            constexpr int phobos_exponent_limit = 0x7FFFFFFF / 10 - 10;
            if (parsed_exponent < phobos_exponent_limit) {
                parsed_exponent = parsed_exponent * 10 + digit;
            }
            exponent_digits = true;
        }
        if (!exponent_digits) invalid_real80(input);
        add_exponent(negative_exponent ? -parsed_exponent : parsed_exponent);
    }

    Real80 value = Real80::fromUnsigned(msdec);
    if (msscale != 1) {
        value = value * Real80::fromUnsigned(msscale) + Real80::fromUnsigned(lsdec);
    }
    if (is_hexadecimal) {
        // Phobosと同様、ここでは ldexp を呼び、結果がゼロでも拒否しない。
        value = value.scaledByPowerOfTwo(exponent);
    } else if (!value.isZero()) {
        unsigned int table_index = 0;
        int power = 4096;
        while (exponent > 0) {
            while (exponent >= power) {
                if (table_index >= positive_powers().size()) {
                    // Phobosは表の全範囲を超える指数で postab
                    // の外を参照し、進まなくなる場合がある。
                    // 範囲外アクセスは再現せず、拒否する。
                    invalid_real80(input);
                }
                value = value * positive_powers()[table_index];
                exponent -= power;
            }
            power >>= 1;
            ++table_index;
        }
        table_index = 0;
        power = 4096;
        while (exponent < 0) {
            while (exponent <= -power) {
                if (table_index >= negative_powers().size()) {
                    // Phobosの negtab は固定長。途中結果がゼロ
                    // になる検査で終了しなかった場合も、表の外を参照しない。
                    invalid_real80(input);
                }
                value = value * negative_powers()[table_index];
                if (value.isZero()) invalid_real80(input);
                exponent += power;
            }
            power >>= 1;
            ++table_index;
        }
    }

    if (negative) value = -value;
    // Target=real の場合の、Phobosの最後の isFinite(result) 検査に相当する。
    if (!value.isFinite()) invalid_real80(input);
    if (position != input.size()) invalid_real80(input);
    return value;
}

